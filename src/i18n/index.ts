export function translate(locale: Locale, key: MessageKey, variables?: Record<string, string | number>): string {
  let output: string = messages[locale][key] ?? messages.en[key];
  for (const [name, replacement] of Object.entries(variables ?? {})) {
    output = output.replaceAll(`{${name}}`, String(replacement));
  }
  return output;
}
